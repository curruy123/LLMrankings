"""
03_compare_rankings.py — Part C: how much do rankings change across tasks,
and how much of that change is just sampling noise?

Run:  python 03_compare_rankings.py   (after 01 and 02)

Analyses per category c (math, coding, creative writing):
  1. Spearman correlation between the category ranking and the overall
     ranking, on (a) all 52 models and (b) models reliably estimated in c.
  2. Rank-change table with bootstrap rank intervals.
  3. NULL SIMULATION (parametric bootstrap). If task did not matter, the
     category data would be generated by the overall strengths (allowing the
     category to be more or less "discriminating": theta_c = kappa * theta).
     We simulate outcomes for the *same* category matchups under that null,
     refit, and record Spearman and each model's rank change. Observed changes
     that are typical of the null are consistent with pure sampling noise.
  4. JOINT "category vs rest" models fitted to all English decisive data, so
     that category and non-category strengths are estimated in ONE likelihood
     (same data, same scale, same centering):
        same  : theta shared                               (no task effect)
        scale : theta_c = kappa * theta_rest               (same ranking, different spread)
        sep   : theta_c and theta_rest free                (task-specific ranking)
     LR(sep vs same) tests "do strengths differ at all?"; LR(sep vs scale)
     tests "do RANKINGS differ beyond a uniform stretch?". A session-robust
     Wald test of sep vs same is also reported.
  5. Specialisation: delta_i = theta_c,i - kappa * theta_rest,i with robust SE
     and Benjamini–Hochberg q-values.

Why not compare raw thetas across separate fits?  Each separate fit is
centred on its own average model and the spread of theta depends on how
decisive the votes in that category are. Ranks are scale-free; the joint
models above put both on a single likelihood and make kappa explicit.

Outputs (./outputs/ and ./outputs/figures/):
    rank_changes.csv, ranking_comparison_summary.csv, category_rank_matrix.csv,
    specialisation.csv, null_simulation_spearman.csv
    figures/rank_scatter.png, rank_heatmap.png, largest_shifts.png,
    spearman_null.png, specialisation.png
"""
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy.optimize import minimize_scalar
from scipy.special import expit
from scipy.stats import chi2, spearmanr

import btl
from common import (CATEGORIES, COLORS, FIG, GRID, INK, INK2, OUT, SEED,
                    load_decisive, section)

N_NULL = 200
pd.set_option("display.width", 220)

dec = load_decisive()
overall = pd.read_csv(OUT / "overall_ranking.csv", index_col=0)
models = sorted(overall.index)
K = len(models)
A = btl._contrast_basis(K)
Xb_all = btl._design(dec, models) @ A          # n x (K-1), dense
y_all = dec.y.to_numpy(float)
sess = pd.factorize(dec.evaluation_session_id)[0]
cat_tables = {c: pd.read_csv(OUT / f"{c}_ranking.csv", index_col=0) for c in CATEGORIES}
rng = np.random.default_rng(SEED)


def bh(p):
    """Benjamini–Hochberg q-values."""
    p = np.asarray(p)
    o = np.argsort(p)
    q = p[o] * len(p) / np.arange(1, len(p) + 1)
    q = np.minimum.accumulate(q[::-1])[::-1]
    out = np.empty_like(q)
    out[o] = np.minimum(q, 1)
    return out


summary, changes, spec_rows, null_rows = [], [], [], []
for c, name in CATEGORIES.items():
    section(name.upper())
    t = cat_tables[c]
    ind = dec[c].to_numpy(float)
    rest = 1 - ind
    G2 = np.column_stack([rest, ind])               # separate gammas

    # ---------- joint models ----------
    same = btl.fit_logistic(np.column_stack([Xb_all, G2]), y_all)
    sep = btl.fit_logistic(np.column_stack([Xb_all * rest[:, None], Xb_all * ind[:, None], G2]),
                           y_all, cluster_codes=sess)

    def scale_ll(k):
        return -btl.fit_logistic(np.column_stack([Xb_all * (rest + k * ind)[:, None], G2]),
                                 y_all)["loglik"]
    opt = minimize_scalar(scale_ll, bounds=(0.2, 3.0), method="bounded",
                          options={"xatol": 1e-4})
    kappa, ll_scale = opt.x, -opt.fun
    # profile-likelihood 95% CI for kappa
    grid = np.linspace(max(0.2, kappa - 0.6), kappa + 0.6, 61)
    prof = np.array([-scale_ll(k) for k in grid])
    ok = grid[ll_scale - prof <= chi2.ppf(0.95, 1) / 2]
    k_lo, k_hi = ok.min(), ok.max()

    lr_any = 2 * (sep["loglik"] - same["loglik"])
    lr_rank = 2 * (sep["loglik"] - ll_scale)
    b_rest, b_cat = sep["par"][:K - 1], sep["par"][K - 1:2 * (K - 1)]
    V = sep["cov_robust"]
    Vrr, Vcc = V[:K - 1, :K - 1], V[K - 1:2 * (K - 1), K - 1:2 * (K - 1)]
    Vrc = V[:K - 1, K - 1:2 * (K - 1)]
    db = b_cat - b_rest
    Vd = Vcc + Vrr - Vrc - Vrc.T
    wald = float(db @ np.linalg.solve(Vd, db))
    print(f"kappa (category spread relative to rest) = {kappa:.3f} "
          f"[95% profile CI {k_lo:.2f}, {k_hi:.2f}]")
    print(f"LR sep vs same  (any difference):      {lr_any:8.1f} on {K - 1} df, p = {chi2.sf(lr_any, K - 1):.2e}")
    print(f"robust Wald sep vs same:               {wald:8.1f} on {K - 1} df, p = {chi2.sf(wald, K - 1):.2e}")
    print(f"LR sep vs scale (ranking difference):  {lr_rank:8.1f} on {K - 2} df, p = {chi2.sf(lr_rank, K - 2):.2e}")

    # ---------- specialisation ----------
    dk = b_cat - kappa * b_rest
    Vk = Vcc + kappa ** 2 * Vrr - kappa * (Vrc + Vrc.T)
    delta = A @ dk
    se = np.sqrt(np.diag(A @ Vk @ A.T))
    z = delta / se
    from scipy.stats import norm
    pval = 2 * norm.sf(np.abs(z))
    q = bh(pval)
    spec = pd.DataFrame({"category": c, "delta": delta, "se": se, "z": z, "p": pval,
                         "q_bh": q}, index=models)
    spec["reliable_in_category"] = t["reliable"].reindex(models)
    spec["specialist"] = np.where((spec.q_bh < 0.10) & spec.reliable_in_category,
                                  np.where(spec.delta > 0, "stronger", "weaker"), "")
    spec_rows.append(spec)
    sig = spec[spec.specialist != ""].sort_values("delta", ascending=False)
    print(f"models with significant category-specific deviation (BH q < 0.10, reliable): {len(sig)}")
    print(sig[["delta", "se", "z", "q_bh", "specialist"]].round(3).to_string() if len(sig) else "  none")

    # ---------- observed rank agreement ----------
    common_all = t.index.intersection(overall.index)
    rel = t.index[t.reliable].intersection(overall.index)
    rho_all = spearmanr(overall.loc[common_all, "rank"], t.loc[common_all, "rank"])[0]
    rho_rel = spearmanr(overall.loc[rel, "rank"], t.loc[rel, "rank"])[0]
    br = pd.read_csv(OUT / f"{c}_bootstrap_ranks.csv")
    boot_rho = np.array([spearmanr(overall.loc[common_all, "rank"],
                                   br.loc[i, common_all].to_numpy())[0]
                         for i in range(len(br)) if br.loc[i, common_all].notna().all()])

    # ---------- null simulation ----------
    sub = dec[dec[c]]
    th0 = kappa * overall["theta"]
    gamma_c = sep["par"][-1]
    p0 = expit(sub.model_a.map(th0).to_numpy() - sub.model_b.map(th0).to_numpy() + gamma_c)
    sim_rho_all, sim_rho_rel, sim_shift = [], [], []
    cm = sorted(btl.model_counts(sub).index)
    for s in range(N_NULL):
        d = sub.copy()
        d["y"] = (rng.random(len(d)) < p0).astype(float)
        f = btl.fit_btl(d, cm, cluster=None)
        r = f["theta"].rank(ascending=False, method="first")
        sim_rho_all.append(spearmanr(overall.loc[common_all, "rank"], r[common_all])[0])
        sim_rho_rel.append(spearmanr(overall.loc[rel, "rank"], r[rel])[0])
        sim_shift.append((overall.loc[cm, "rank"] - r[cm]).abs())
    sim_shift = pd.concat(sim_shift, axis=1)
    sim_rho_all, sim_rho_rel = np.array(sim_rho_all), np.array(sim_rho_rel)
    p_rho = (np.sum(sim_rho_all <= rho_all) + 1) / (N_NULL + 1)
    p_rho_rel = (np.sum(sim_rho_rel <= rho_rel) + 1) / (N_NULL + 1)
    null_rows.append(pd.DataFrame({"category": c, "sim": np.arange(N_NULL),
                                   "spearman_all": sim_rho_all,
                                   "spearman_reliable": sim_rho_rel}))
    print(f"Spearman vs overall, all {len(common_all)} models: {rho_all:.3f} "
          f"(bootstrap 95% CI {np.quantile(boot_rho, .025):.3f}-{np.quantile(boot_rho, .975):.3f})")
    print(f"  null (no task effect) median {np.median(sim_rho_all):.3f}, 95% range "
          f"{np.quantile(sim_rho_all, .025):.3f}-{np.quantile(sim_rho_all, .975):.3f}; "
          f"P(null <= observed) = {p_rho:.3f}")
    print(f"Spearman vs overall, {len(rel)} reliable models: {rho_rel:.3f}; null median "
          f"{np.median(sim_rho_rel):.3f}, P = {p_rho_rel:.3f}")

    # ---------- rank-change table ----------
    ch = pd.DataFrame({
        "category": c,
        "overall_rank": overall.loc[common_all, "rank"],
        "category_rank": t.loc[common_all, "rank"],
    })
    ch["rank_change"] = ch.overall_rank - ch.category_rank       # + = better in category
    ch["category_rank_ci"] = (t.loc[common_all, "rank_ci_low"].astype(str) + "-" +
                              t.loc[common_all, "rank_ci_high"].astype(str))
    ch["overall_rank_in_category_ci"] = ((ch.overall_rank >= t.loc[common_all, "rank_ci_low"]) &
                                         (ch.overall_rank <= t.loc[common_all, "rank_ci_high"]))
    ch["n_category"] = t.loc[common_all, "n_comparisons"]
    ch["reliable"] = t.loc[common_all, "reliable"]
    obs = ch.rank_change.abs()
    ch["null_expected_abs_change"] = sim_shift.reindex(common_all).mean(axis=1)
    ch["null_p_abs_change"] = [(np.sum(sim_shift.loc[m] >= obs[m]) + 1) / (N_NULL + 1)
                               for m in common_all]
    ch = ch.join(spec[["delta", "se", "q_bh", "specialist"]].rename(
        columns={"delta": "spec_delta", "se": "spec_se", "q_bh": "spec_q"}))
    changes.append(ch)
    show = ch.sort_values("rank_change")
    print("largest drops / gains (all models):")
    print(pd.concat([show.head(4), show.tail(4)])[[
        "overall_rank", "category_rank", "rank_change", "category_rank_ci", "n_category",
        "reliable", "null_expected_abs_change", "null_p_abs_change", "spec_q"]].round(3).to_string())

    summary.append({
        "category": c, "n_comparisons": len(sub), "kappa": kappa, "kappa_ci_low": k_lo,
        "kappa_ci_high": k_hi, "lr_any": lr_any, "p_any": chi2.sf(lr_any, K - 1),
        "wald_robust_any": wald, "p_wald_any": chi2.sf(wald, K - 1),
        "lr_ranking": lr_rank, "p_ranking": chi2.sf(lr_rank, K - 2), "df_ranking": K - 2,
        "spearman_all": rho_all, "spearman_all_boot_lo": np.quantile(boot_rho, .025),
        "spearman_all_boot_hi": np.quantile(boot_rho, .975),
        "null_spearman_all_median": np.median(sim_rho_all),
        "null_spearman_all_lo": np.quantile(sim_rho_all, .025),
        "p_spearman_all_vs_null": p_rho, "n_reliable": len(rel), "spearman_reliable": rho_rel,
        "null_spearman_reliable_median": np.median(sim_rho_rel), "p_spearman_reliable_vs_null": p_rho_rel,
        "mean_abs_rank_change": obs.mean(), "null_mean_abs_rank_change": sim_shift.mean().mean(),
        "share_overall_rank_inside_category_ci": ch.overall_rank_in_category_ci.mean(),
        "n_specialists_stronger": int((spec.specialist == "stronger").sum()),
        "n_specialists_weaker": int((spec.specialist == "weaker").sum()),
    })

summary = pd.DataFrame(summary)
changes = pd.concat(changes)
spec_all = pd.concat(spec_rows)
null_df = pd.concat(null_rows)
summary.to_csv(OUT / "ranking_comparison_summary.csv", index=False)
changes.rename_axis("model").to_csv(OUT / "rank_changes.csv")
spec_all.rename_axis("model").to_csv(OUT / "specialisation.csv")
null_df.to_csv(OUT / "null_simulation_spearman.csv", index=False)
mat = pd.DataFrame({"Overall": overall["rank"]})
for c, name in CATEGORIES.items():
    mat[name] = cat_tables[c]["rank"]
mat = mat.sort_values("Overall")
mat.rename_axis("model").to_csv(OUT / "category_rank_matrix.csv")
section("SUMMARY")
print(summary.round(4).T.to_string())

